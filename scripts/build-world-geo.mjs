// 2026-11-10: generates src/world-geo.js — raw lon/lat geometry for the TRUE
// 3D orthographic globes (owner request: "redesign, completely free rotation,
// more accurate with countries at the right place"). The old equirectangular
// strip (world-land.js) could never rotate like a sphere, so the globes now
// project real Natural Earth 110m geometry orthographically at runtime.
// Source: the world-atlas npm package (Natural Earth, public domain).
//   • LAND  — land polygon rings as [lon,lat,lon,lat,…] flat arrays
//   • BORDERS — interior country borders as polylines (same flat encoding)
// Coordinates are rounded to 2 decimals (~1.1 km — far finer than 110m data).
// Run manually after bumping world-atlas:  node scripts/build-world-geo.mjs
// The output is committed and lives only in the lazy globe chunk, so it never
// touches the first-load budget and the client never fetches map data.
import { readFile, writeFile } from 'node:fs/promises';
import { feature, mesh } from 'topojson-client';

const landTopo = JSON.parse(await readFile(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url), 'utf8'));
const ctryTopo = JSON.parse(await readFile(new URL('../node_modules/world-atlas/countries-110m.json', import.meta.url), 'utf8'));

const r2 = n => Math.round(n * 100) / 100;

// Shoelace area in deg² — drop invisible specks to keep the file small.
const ringArea = ring => {
  let a = 0;
  for (let i = 0; i < ring.length; i++) {
    const [x1, y1] = ring[i], [x2, y2] = ring[(i + 1) % ring.length];
    a += x1 * y2 - x2 * y1;
  }
  return Math.abs(a / 2);
};

const flatten = ring => {
  const out = [];
  let px = null, py = null;
  for (const [lon, lat] of ring) {
    const x = r2(lon), y = r2(lat);
    if (x === px && y === py) continue;
    px = x; py = y;
    out.push(x, y);
  }
  return out;
};

const land = feature(landTopo, landTopo.objects.land);
const rings = [];
for (const f of (land.type === 'FeatureCollection' ? land.features : [land])) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      if (ringArea(ring) < 0.35) continue; // sub-speck islands
      const flat = flatten(ring);
      if (flat.length >= 8) rings.push(flat);
    }
  }
}

// Interior borders only (a !== b): coastlines already outline the land fill.
const borderMesh = mesh(ctryTopo, ctryTopo.objects.countries, (a, b) => a !== b);
const borders = [];
for (const line of borderMesh.coordinates) {
  const flat = flatten(line);
  if (flat.length >= 4) borders.push(flat);
}

const enc = arr => JSON.stringify(arr);
const out = `// GENERATED by scripts/build-world-geo.mjs — do not edit by hand.
// Natural Earth 110m via world-atlas (public domain). Flat [lon,lat,…] arrays.
export const LAND = ${enc(rings)};
export const BORDERS = ${enc(borders)};
`;
await writeFile(new URL('../src/world-geo.js', import.meta.url), out);
const pts = rings.reduce((n, r) => n + r.length / 2, 0);
console.log(`world-geo.js written: ${rings.length} land rings (${pts} pts), ${borders.length} border lines, ${(out.length / 1024).toFixed(1)} KB`);
