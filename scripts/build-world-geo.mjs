// 2026-11-10: generates src/world-geo.js — raw lon/lat geometry for the TRUE
// 3D orthographic globes (owner request: "redesign, completely free rotation,
// more accurate with countries at the right place"). The old equirectangular
// strip (world-land.js) could never rotate like a sphere, so the globes now
// project real Natural Earth 110m geometry orthographically at runtime.
// Source: the world-atlas npm package (Natural Earth, public domain).
//   • LAND  — land polygon rings as [lon,lat,lon,lat,…] flat arrays
//   • BORDERS — interior country borders as polylines (same flat encoding)
// Coordinates are rounded to 2 decimals (~1.1 km — far finer than 110m data).
// Run manually after bumping world-atlas:  node scripts/build-world-geo.mjs
// The output is committed and lives only in the lazy globe chunk, so it never
// touches the first-load budget and the client never fetches map data.
import { readFile, writeFile } from 'node:fs/promises';
import { feature, mesh } from 'topojson-client';
import earcut from 'earcut';

const landTopo = JSON.parse(await readFile(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url), 'utf8'));
const ctryTopo = JSON.parse(await readFile(new URL('../node_modules/world-atlas/countries-110m.json', import.meta.url), 'utf8'));

const r2 = n => Math.round(n * 100) / 100;
const r1 = n => Math.round(n * 10) / 10;

// Shoelace area in deg² — drop invisible specks to keep the file small.
const ringArea = ring => {
  let a = 0;
  for (let i = 0; i < ring.length; i++) {
    const [x1, y1] = ring[i], [x2, y2] = ring[(i + 1) % ring.length];
    a += x1 * y2 - x2 * y1;
  }
  return Math.abs(a / 2);
};

const flatten = (ring, round = r2) => {
  const out = [];
  let px = null, py = null;
  for (const [lon, lat] of ring) {
    const x = round(lon), y = round(lat);
    if (x === px && y === py) continue;
    px = x; py = y;
    out.push(x, y);
  }
  // drop the GeoJSON closing point (first === last) — earcut wants open rings
  if (out.length >= 4 && out[0] === out[out.length - 2] && out[1] === out[out.length - 1]) out.length -= 2;
  return out;
};

// 2026-11-10 (owner: "water turned gold while rotating"): the land is now
// TRIANGULATED at build time. Filling whole clamped rings let a half-hidden
// continent close its polygon across open ocean; tiny triangles can never do
// that — each one covers only its own patch of land, so the sea stays green
// at every rotation. Output per polygon: v = flat [lon,lat,…] (outer ring
// then holes), o = ring start offsets (for coastline strokes), t = earcut
// triangle indices into v.
const land = feature(landTopo, landTopo.objects.land);
const POLYS = [];
for (const f of (land.type === 'FeatureCollection' ? land.features : [land])) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    const outer = poly[0];
    if (ringArea(outer) < 0.35) continue; // sub-speck islands
    const v = flatten(outer);
    if (v.length < 6) continue;
    const offsets = [0];
    const holeIdx = [];
    for (const hole of poly.slice(1)) {
      if (ringArea(hole) < 0.35) continue;
      const h = flatten(hole);
      if (h.length < 6) continue;
      holeIdx.push(v.length / 2);
      offsets.push(v.length / 2);
      v.push(...h);
    }
    const t = earcut(v, holeIdx.length ? holeIdx : null, 2);
    if (t.length >= 3) POLYS.push({ v, o: offsets, t });
  }
}

// Interior borders only (a !== b): coastlines already outline the land fill.
const borderMesh = mesh(ctryTopo, ctryTopo.objects.countries, (a, b) => a !== b);
const borders = [];
for (const line of borderMesh.coordinates) {
  const flat = flatten(line);
  if (flat.length >= 4) borders.push(flat);
}

// 2026-11-11 (owner: "do all the globe upgrades"): named country polygons
// for hover/tap COUNTRY TOOLTIPS + highlight on the globes. 0.1° rounding
// (~11 km) is finer than the 110m source itself; rings keep holes — the
// engine hit-tests with even-odd ray casting, so holes just work.
const ctries = feature(ctryTopo, ctryTopo.objects.countries);
const COUNTRIES = [];
for (const f of ctries.features) {
  const name = String(f.properties?.name || '').trim();
  if (!name || !f.geometry) continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = [];
  for (const poly of polys) {
    for (const ring of poly) {
      if (ringArea(ring) < 0.45) continue; // specks: invisible at globe scale
      const flat = flatten(ring, r1);
      if (flat.length >= 8) rings.push(flat);
    }
  }
  if (rings.length) COUNTRIES.push({ n: name, r: rings });
}

const enc = arr => JSON.stringify(arr);
const out = `// GENERATED by scripts/build-world-geo.mjs — do not edit by hand.
// Natural Earth 110m via world-atlas (public domain).
// LAND: [{v:[lon,lat,…], o:[ring offsets], t:[triangle indices]}] — see the
// triangulation note in the generator. BORDERS: flat [lon,lat,…] polylines.
export const LAND = ${enc(POLYS)};
export const BORDERS = ${enc(borders)};
export const COUNTRIES = ${enc(COUNTRIES)};
`;
await writeFile(new URL('../src/world-geo.js', import.meta.url), out);
const pts = POLYS.reduce((n, p) => n + p.v.length / 2, 0);
const tris = POLYS.reduce((n, p) => n + p.t.length / 3, 0);
const cpts = COUNTRIES.reduce((n, c) => n + c.r.reduce((m, r) => m + r.length / 2, 0), 0);
console.log(`world-geo.js written: ${POLYS.length} land polygons (${pts} pts, ${tris} triangles), ${borders.length} border lines, ${COUNTRIES.length} named countries (${cpts} pts), ${(out.length / 1024).toFixed(1)} KB`);
