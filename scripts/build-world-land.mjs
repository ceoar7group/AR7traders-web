// 2026-11-09: generates src/world-land.js — a REAL equirectangular world map
// for the AR7 globes (owner request: "more realistic map"). Source is Natural
// Earth 110m via the world-atlas npm package, projected with the exact same
// X/Y mapping network.jsx has always used:
//   X = (lon + 180) / 360 * 1000      Y = 125 + (90 - lat) / 180 * 750
// Run manually after bumping world-atlas:  node scripts/build-world-land.mjs
// The output is committed, so neither the build nor the client ever fetches
// map data at runtime.
import { readFile, writeFile } from 'node:fs/promises';
import { feature, mesh } from 'topojson-client';

const landTopo = JSON.parse(await readFile(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url), 'utf8'));
const ctryTopo = JSON.parse(await readFile(new URL('../node_modules/world-atlas/countries-110m.json', import.meta.url), 'utf8'));

const X = lon => (lon + 180) / 360 * 1000;
const Y = lat => 125 + (90 - lat) / 180 * 750;
const fmt = n => { const s = n.toFixed(1); return s.endsWith('.0') ? s.slice(0, -2) : s; };

const ringToPath = ring => {
  let minx = 1e9, maxx = -1e9, miny = 1e9, maxy = -1e9;
  const pts = ring.map(([lo, la]) => {
    const x = X(lo), y = Y(la);
    if (x < minx) minx = x; if (x > maxx) maxx = x;
    if (y < miny) miny = y; if (y > maxy) maxy = y;
    return [x, y];
  });
  if ((maxx - minx) * (maxy - miny) < 5) return ''; // drop sub-5px² specks
  let prevKey = null; const segs = [];
  for (const [x, y] of pts) {
    const k = fmt(x) + ' ' + fmt(y);
    if (k === prevKey) continue;
    prevKey = k; segs.push(k);
  }
  return segs.length < 3 ? '' : 'M' + segs.join('L') + 'Z';
};

const land = feature(landTopo, landTopo.objects.land);
const landFeatures = land.type === 'FeatureCollection' ? land.features : [land];
let landPath = '';
for (const f of landFeatures) {
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const poly of polys) for (const ring of poly) landPath += ringToPath(ring);
}

// Interior country borders only (a !== b) — drawn as a hairline over the land.
const borders = mesh(ctryTopo, ctryTopo.objects.countries, (a, b) => a !== b);
let borderPath = '';
for (const line of borders.coordinates) {
  let prevKey = null; const segs = [];
  for (const [lo, la] of line) {
    const k = fmt(X(lo)) + ' ' + fmt(Y(la));
    if (k === prevKey) continue;
    prevKey = k; segs.push(k);
  }
  if (segs.length >= 2) borderPath += 'M' + segs.join('L');
}

const out = `// GENERATED by scripts/build-world-land.mjs — do not edit by hand.
// Natural Earth 110m (world-atlas@2) projected to the AR7 globe's
// equirectangular space: X=(lon+180)/360*1000, Y=125+(90-lat)/180*750.
// Lives in its own lazy chunk (network.jsx is lazy; main.jsx imports this
// dynamically), so it never weighs on the first-load bundle budget.
export const WORLD_LAND_PATH = '${landPath}';
export const WORLD_BORDER_PATH = '${borderPath}';
`;
await writeFile(new URL('../src/world-land.js', import.meta.url), out);
console.log('land path:', (landPath.length / 1024).toFixed(1) + ' kB;', 'borders:', (borderPath.length / 1024).toFixed(1) + ' kB');
