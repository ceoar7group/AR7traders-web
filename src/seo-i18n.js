/** [title, description] of a static page in `lang`, or null when the page
 *  has no localized entry (dynamic pages, legal pages, staff routes) or the
 *  language is English. Callers fall back to PAGE_SEO. */
export function localizedPageSeo(page, lang) {
  if (!lang || lang === 'en') return null;
  const entry = PAGE_SEO_I18N[lang]?.[page];
  return Array.isArray(entry) && entry.length === 2 ? entry : null;
}
